-- Hub store: the events ledger, the outbox and the approvals in Postgres, one schema per store
-- instance (live: hub; tests: t_*). Plain, forward-only SQL; hubd applies each file once per schema (schema_migrations).
-- Columns map 1:1 to the SQLite stores (schemas/events.sql + events-v2.sql, schemas/approvals.sql): the same names,
-- JSON kept as TEXT (byte-identical round trips), REAL -> DOUBLE PRECISION, INTEGER ids -> BIGINT identities.
-- Ids born in the hub start at 10000000 for events and outbox, so they never meet the ids the in-container SQLite
-- store hands out.
CREATE TABLE IF NOT EXISTS events(id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10000000) PRIMARY KEY,
  ts DOUBLE PRECISION NOT NULL, source TEXT NOT NULL, kind TEXT NOT NULL,
  subject TEXT NOT NULL DEFAULT '', next TEXT NOT NULL DEFAULT '', payload TEXT NOT NULL DEFAULT '{}',
  labels TEXT NOT NULL DEFAULT '[]', delivery TEXT NOT NULL DEFAULT 'beat', trace_id TEXT, idem_key TEXT UNIQUE,
  note_path TEXT, status TEXT NOT NULL DEFAULT 'new',  -- new|listed|acked|dismissed|gone
  updated_ts DOUBLE PRECISION, first_beat BIGINT, first_listed_ts DOUBLE PRECISION, acked_ts DOUBLE PRECISION,
  ack_by TEXT, ack_note TEXT);
CREATE INDEX IF NOT EXISTS events_status ON events(status, ts);
CREATE TABLE IF NOT EXISTS beats(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ts DOUBLE PRECISION NOT NULL,
  source TEXT, ok INTEGER, ms INTEGER, chars INTEGER, listed TEXT);
CREATE INDEX IF NOT EXISTS beats_ts ON beats(ts);
CREATE TABLE IF NOT EXISTS wake_rules(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created DOUBLE PRECISION NOT NULL, kind_glob TEXT, klass TEXT NOT NULL, until DOUBLE PRECISION, why TEXT,
  active INTEGER NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS meta(k TEXT PRIMARY KEY, v TEXT);
CREATE TABLE IF NOT EXISTS outbox(id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10000000) PRIMARY KEY,
  ts DOUBLE PRECISION NOT NULL, bot TEXT NOT NULL, chat TEXT NOT NULL, op TEXT NOT NULL, body TEXT NOT NULL,
  idem_key TEXT UNIQUE, urgent INTEGER NOT NULL DEFAULT 0, not_before DOUBLE PRECISION,
  mode TEXT NOT NULL DEFAULT 'live', status TEXT NOT NULL DEFAULT 'queued',  -- queued|sending|sent|failed|skipped
  attempts INTEGER NOT NULL DEFAULT 0, last_error TEXT, sent_ts DOUBLE PRECISION, tg_message_id BIGINT,
  trace_id TEXT, reply_to_event BIGINT, files TEXT, result TEXT);
CREATE INDEX IF NOT EXISTS outbox_queue ON outbox(status, bot, id);
CREATE TABLE IF NOT EXISTS deliveries(event_id BIGINT PRIMARY KEY, sent_ts DOUBLE PRECISION,
  tries INTEGER NOT NULL DEFAULT 0, receipt_ts DOUBLE PRECISION, how TEXT);
CREATE TABLE IF NOT EXISTS bindings(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind TEXT NOT NULL,
  key TEXT NOT NULL, tool TEXT NOT NULL, args TEXT NOT NULL DEFAULT '[]', note INTEGER NOT NULL DEFAULT 0,
  on_error TEXT NOT NULL DEFAULT 'reply', why TEXT NOT NULL, created DOUBLE PRECISION NOT NULL,
  expires DOUBLE PRECISION, active INTEGER NOT NULL DEFAULT 1, UNIQUE(kind, key));
CREATE TABLE IF NOT EXISTS approvals(nonce TEXT PRIMARY KEY, action_sha TEXT NOT NULL,
  summary TEXT NOT NULL DEFAULT '', ref TEXT, chat TEXT, message_id BIGINT, created DOUBLE PRECISION NOT NULL,
  expires DOUBLE PRECISION NOT NULL, status TEXT NOT NULL DEFAULT 'pending',  -- pending|approved|denied|expired|cancelled
  decided_ts DOUBLE PRECISION, decided_by TEXT, decided_via TEXT, used_ts DOUBLE PRECISION, used_by TEXT,
  refused INTEGER NOT NULL DEFAULT 0, card TEXT);
CREATE INDEX IF NOT EXISTS approvals_status ON approvals(status, expires);
-- Write requests the hub already answered (a client's retry after a lost answer gets the same result, never a
-- second write). Pruned after 7 days.
CREATE TABLE IF NOT EXISTS requests(rid TEXT PRIMARY KEY, ts DOUBLE PRECISION NOT NULL, caller TEXT NOT NULL,
  op TEXT NOT NULL, result TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS requests_ts ON requests(ts);
-- Outbox consumers (the tg caller's adapter): bot keys it drains and when it last asked for rows. The brain's gate
-- sends through the hub outbox only while a consumer for its bot key was seen recently.
CREATE TABLE IF NOT EXISTS consumers(bot TEXT PRIMARY KEY, caller TEXT NOT NULL, seen DOUBLE PRECISION NOT NULL);
