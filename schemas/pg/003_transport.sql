-- The Telegram transport on the hub (forward-only, additive). Transport rows (tg.*, outbox.*,
-- approval.*, bridge.*) already fit events/deliveries/bindings (001); this adds the companion's jobs and the
-- indexes the transport reads use (the bridge's inbound poll, receipts, brain-watch, tgmetrics).
CREATE TABLE IF NOT EXISTS tg_jobs(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind TEXT NOT NULL,
  args TEXT NOT NULL, timeout_s INTEGER NOT NULL, state TEXT NOT NULL DEFAULT 'queued',  -- queued|running|done|failed|unclaimed|expired
  created DOUBLE PRECISION NOT NULL, claimed_ts DOUBLE PRECISION, done_ts DOUBLE PRECISION, result TEXT, error TEXT);
CREATE INDEX IF NOT EXISTS tg_jobs_queue ON tg_jobs(state, kind, id);
CREATE INDEX IF NOT EXISTS tg_jobs_created ON tg_jobs(created);
CREATE INDEX IF NOT EXISTS events_now_id ON events(id) WHERE delivery = 'now';
CREATE INDEX IF NOT EXISTS events_kind_ts ON events(kind, ts);
CREATE INDEX IF NOT EXISTS events_source_ts ON events(source, ts);
CREATE INDEX IF NOT EXISTS deliveries_receipt_ts ON deliveries(receipt_ts) WHERE receipt_ts IS NOT NULL;
CREATE INDEX IF NOT EXISTS deliveries_sent_ts ON deliveries(sent_ts);
CREATE INDEX IF NOT EXISTS outbox_ts ON outbox(ts);
CREATE INDEX IF NOT EXISTS outbox_reply_to ON outbox(reply_to_event) WHERE reply_to_event IS NOT NULL;
