-- Board: the board as records. The brain's `board` CLI is the only writer (hubboard routes,
-- caller brain); TODO.md and the dashboard render these rows. kind item = one "- " line + its sub-bullets (notes),
-- kind raw = lines kept verbatim (blank lines, comments, the tasks block). probes = JSON list of done-when checks.
CREATE TABLE IF NOT EXISTS board_items(id TEXT PRIMARY KEY, kind TEXT NOT NULL DEFAULT 'item', section TEXT NOT NULL,
  pos DOUBLE PRECISION NOT NULL, line TEXT NOT NULL, title TEXT NOT NULL DEFAULT '', notes TEXT NOT NULL DEFAULT '[]',
  due_ts DOUBLE PRECISION, probes TEXT NOT NULL DEFAULT '[]', state TEXT NOT NULL DEFAULT 'open',  -- open|done|dropped
  created DOUBLE PRECISION NOT NULL, updated DOUBLE PRECISION NOT NULL, closed_ts DOUBLE PRECISION, closed_by TEXT,
  version INTEGER NOT NULL DEFAULT 1);
CREATE INDEX IF NOT EXISTS board_items_state ON board_items(state, pos);
CREATE INDEX IF NOT EXISTS board_items_closed ON board_items(closed_ts) WHERE closed_ts IS NOT NULL;
CREATE TABLE IF NOT EXISTS board_log(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ts DOUBLE PRECISION NOT NULL,
  item TEXT, op TEXT NOT NULL, by_who TEXT NOT NULL, detail TEXT NOT NULL DEFAULT '');
CREATE INDEX IF NOT EXISTS board_log_item ON board_log(item, id);
CREATE TABLE IF NOT EXISTS board_meta(k TEXT PRIMARY KEY, v TEXT NOT NULL, updated DOUBLE PRECISION NOT NULL);
